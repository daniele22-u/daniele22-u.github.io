(() => {
  const root = document.documentElement;
  const nodes = document.querySelectorAll('[data-i18n]');
  const EN = {};
  nodes.forEach(n => { EN[n.dataset.i18n] = n.innerHTML; });
  // righe meta dei progetti: in italiano traduco solo mesi e città
  const metas = [...document.querySelectorAll('.ch-meta')].map(n => [n, n.innerHTML]);
  const MONTHS = { Jan: 'gen', Feb: 'feb', Mar: 'mar', Apr: 'apr', May: 'mag', Jun: 'giu', Jul: 'lug', Aug: 'ago', Sept: 'set', Oct: 'ott', Nov: 'nov', Dec: 'dic', Milan: 'Milano' };
  EN['meta.title'] = document.title;
  const desc = document.querySelector('meta[name="description"]');
  EN['meta.desc'] = desc ? desc.content : '';

  function apply(lang) {
    const dict = lang === 'it' ? window.I18N_IT : EN;
    nodes.forEach(n => {
      const v = dict[n.dataset.i18n];
      if (v !== undefined) n.innerHTML = v;
    });
    metas.forEach(([n, en]) => {
      n.innerHTML = lang === 'it' ? en.replace(/\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sept|Oct|Nov|Dec|Milan)\b/g, m => MONTHS[m]) : en;
    });
    document.title = dict['meta.title'];
    if (desc) desc.content = dict['meta.desc'];
    root.lang = lang;
    root.dataset.lang = lang;
    window.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
  }

  let lang = 'en';
  try {
    const saved = localStorage.getItem('lang');
    if (saved === 'it' || saved === 'en') lang = saved;
    else if ((navigator.language || '').toLowerCase().startsWith('it')) lang = 'it';
  } catch (e) {}
  if (new URLSearchParams(location.search).get('lang') === 'it') lang = 'it';
  if (new URLSearchParams(location.search).get('lang') === 'en') lang = 'en';
  apply(lang);

  const btn = document.querySelector('.lang-toggle');
  if (btn) btn.addEventListener('click', () => {
    lang = lang === 'it' ? 'en' : 'it';
    try { localStorage.setItem('lang', lang); } catch (e) {}
    apply(lang);
  });
})();
